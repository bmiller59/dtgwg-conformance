// Refreshes vectors/tf-manifest.json from a local clone of the Trust Tasks task-force repository (read-only git; no fetch).
// Usage: node --experimental-strip-types scripts/tf-manifest.ts --kit <clone> [--main <rev>] [--kit-commit <sha>]
// Defaults: rev origin/main, kit commit 640d498909dc2e0a6b979b8189e8b845c6b86c62. The clone comes from --kit, TT_KIT, or the sibling directory dtgwg-trust-tasks-tf.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { defaultKitRoot } from "../src/vectors/source.ts";
import { TF_MANIFEST_FILE } from "../src/vectors/tfref.ts";
import type { TfManifest } from "../src/vectors/tfref.ts";

const args = process.argv.slice(2);
const opt = (n: string): string | undefined => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : undefined; };
const clone = defaultKitRoot(opt("--kit"));
if (clone === undefined) { console.error("no Trust Tasks clone: pass --kit <dir> or set TT_KIT"); process.exit(2); }
const git = (...a: string[]): string => execFileSync("git", ["-C", clone, ...a], { encoding: "utf8", maxBuffer: 1 << 28 });
const rev = opt("--main") ?? "origin/main";
const mainSha = git("rev-parse", rev).trim();
const kitSha = git("rev-parse", opt("--kit-commit") ?? "640d498909dc2e0a6b979b8189e8b845c6b86c62").trim();
const wanted = (p: string): boolean => /^specs\/.+\/spec\.md$/.test(p) || /^bindings\/\w+\/\d+\.\d+\/spec\.md$/.test(p) || p === "SPEC.md" || p === "ceremonies/ceremony.meta.schema.json";
const list = (sha: string): string[] => git("ls-tree", "-r", "--name-only", sha).split("\n").filter(wanted);
const kit = new Set(list(kitSha));
const paths: TfManifest["paths"] = {};
for (const p of list(mainSha)) {
  let status: "draft" | "retired" | "main" = "main";
  let supersededBy: string | undefined;
  if (p.endsWith("/spec.md") && p.startsWith("specs/")) {
    const fm = /^---\n([\s\S]*?)\n---/.exec(git("show", `${mainSha}:${p}`));
    const st = /^status:\s*(\S+)/m.exec(fm?.[1] ?? "")?.[1]?.replace(/^["']|["']$/g, "");
    status = st === "retired" ? "retired" : "draft";
    if (st !== undefined && st !== "draft" && st !== "retired") throw new Error(`${p}: unexpected status ${st}`);
    const sb = /^supersededBy:\s*(.+)$/m.exec(fm?.[1] ?? "")?.[1]?.trim().replace(/^["']|["']$/g, "");
    if (status === "retired") supersededBy = sb ?? "unknown";
  }
  paths[p] = { status, inKit: kit.has(p), ...(supersededBy === undefined ? {} : { supersededBy }) };
}
const out: TfManifest = {
  format: "tt-tf-manifest/0.1",
  about: "Paths and statuses of the Trust Tasks task-force repository artifacts the vectors may cite (specs/*/spec.md, SPEC.md, bindings, ceremony meta schema). Generated by scripts/tf-manifest.ts from a local clone, read-only; verified again by scripts/resolve-tf-refs.ts when the clone is present. status draft = a registry spec on main, retired = front matter status retired, main = a non-spec document on main.",
  main: { ref: rev, commit: mainSha, date: git("show", "-s", "--format=%cs", mainSha).trim() }, kit: { commit: kitSha }, paths,
};
writeFileSync(TF_MANIFEST_FILE, JSON.stringify(out, null, 2) + "\n");
console.log(`wrote ${TF_MANIFEST_FILE}: ${Object.keys(paths).length} paths, main ${mainSha}, kit ${kitSha}`);
