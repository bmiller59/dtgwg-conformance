// Validates results/interop/ledger.json against the rules in results/interop/ledger.schema.json (no schema library: the
// checks are written out) and renders results/interop/ledger.md. Demonstrated interoperability only; see docs/14.
// Usage: node --experimental-strip-types scripts/interop-ledger-view.ts [--check]
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const PLATFORMS = ["VTI", "keyring-wallet", "truststackers"];
const CARRIERS = ["https", "didcomm-v1", "didcomm-v2", "tsp", "other"];
const OUTCOMES = ["accepted", "rejected-as-specified", "failed", "inconclusive"];

interface Party { platform: string; version: string; surface?: string }
export interface Entry { id: string; date: string; sender: Party; receiver: Party; task: string; version: string; carrier: string; carrierNote?: string; evidence: string[]; outcome: string; outcomeNote?: string; related?: string[] }
export interface Ledger { format: string; entries: Entry[] }

export function validate(l: Ledger): string[] {
  const errs: string[] = [];
  if (l.format !== "tt-interop-ledger/0.1") errs.push("format must be tt-interop-ledger/0.1");
  const seen = new Set<string>();
  for (const [i, e] of (l.entries ?? []).entries()) {
    const at = `entries[${i}]`;
    if (!/^IX-\d{3,}$/.test(e.id ?? "")) errs.push(`${at}.id`);
    if (seen.has(e.id)) errs.push(`${at}.id duplicate`);
    seen.add(e.id);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(e.date ?? "")) errs.push(`${at}.date`);
    for (const role of ["sender", "receiver"] as const) {
      const p = e[role];
      if (!p || !PLATFORMS.includes(p.platform)) errs.push(`${at}.${role}.platform must be one of ${PLATFORMS.join(", ")} (a stand-in is never a party)`);
      if (!p?.version) errs.push(`${at}.${role}.version`);
    }
    if (e.sender?.platform === e.receiver?.platform) errs.push(`${at}: sender and receiver must be different platforms`);
    if (!e.task) errs.push(`${at}.task`);
    if (!/^\d+\.\d+$/.test(e.version ?? "")) errs.push(`${at}.version`);
    if (!CARRIERS.includes(e.carrier)) errs.push(`${at}.carrier`);
    if (!Array.isArray(e.evidence) || e.evidence.length === 0) errs.push(`${at}.evidence (an entry without an artefact is not admitted)`);
    if (!OUTCOMES.includes(e.outcome)) errs.push(`${at}.outcome`);
  }
  return errs;
}

export function render(l: Ledger): string {
  const head = [
    "# Demonstrated-interoperability ledger",
    "",
    "> **Status: draft proposal.** This is a draft proposal for discussion and review by the DTGWG (Trust over IP Decentralized Trust Graph Working Group). It is not an adopted or endorsed standard or test suite. Generated by `scripts/interop-ledger-view.ts` from `ledger.json`. Do not edit by hand. Format and rules: [docs/14](../../docs/14-interoperability-tracking.md).",
    "",
  ];
  if (l.entries.length === 0) {
    return [...head, "**No cross-platform execution has been recorded.** The ledger is empty. Today only conformance-implied evidence exists: see the generated pair matrix. Conformance does not demonstrate interoperation.", ""].join("\n");
  }
  const rows = l.entries.map((e) => `| ${e.id} | ${e.date} | ${e.sender.platform} ${e.sender.version} | ${e.receiver.platform} ${e.receiver.version} | ${e.task}@${e.version} | ${e.carrier} | ${e.evidence.join("<br>")} | ${e.outcome} |`);
  return [...head, "| Id | Date | Sender (client) | Receiver (server) | Task@version | Carrier | Evidence | Outcome |", "|---|---|---|---|---|---|---|---|", ...rows, ""].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const l = JSON.parse(readFileSync(join(root, "results", "interop", "ledger.json"), "utf8")) as Ledger;
  const errs = validate(l);
  if (errs.length) { console.error(errs.join("\n")); process.exit(1); }
  const mp = join(root, "results", "interop", "ledger.md");
  const out = render(l);
  if (process.argv.includes("--check")) { if (!existsSync(mp) || readFileSync(mp, "utf8") !== out) { console.error("ledger.md is out of date"); process.exit(1); } }
  else writeFileSync(mp, out);
}
