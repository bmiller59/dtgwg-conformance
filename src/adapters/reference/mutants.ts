export type MutantId = keyof typeof MUTANTS;

export function isMutantId(id: string): id is MutantId {
  return Object.prototype.hasOwnProperty.call(MUTANTS, id) || Object.prototype.hasOwnProperty.call(BEHAVIOUR_MUTANTS, id) || Object.prototype.hasOwnProperty.call(CEREMONY_MUTANTS, id) || Object.prototype.hasOwnProperty.call(REISSUE_MUTANTS, id) || Object.prototype.hasOwnProperty.call(SEEDED_STATE_MUTANTS, id);
}

/**
 * Deliberately lying reference variants for the adapter honesty check (src/runner/honesty.ts, non-vacuity): each keeps its declared
 * essential governance (ReferenceOptions.essential, stated in its capabilities) but behaves otherwise. They are not vector mutants:
 * no vector names them; the honesty probe, which every suite run applies, must record a declaration mismatch against each
 * (test/honesty.test.ts).
 */
export const DECLARATION_LIES = {
  completesEarly: "declares k but completes the ceremony at k - 1 distinct approvals (declares k = 2, completes at 1)",
  completesLate: "declares k but completes the ceremony only at k + 1 distinct approvals (declares k = 1 of 1, needs a second principal; declares k = 2, completes at 3)",
  anyPrincipalDecides: "declares its authority set but counts a begin or an approval from any principal, inside the set or not",
} as const;

export type DeclarationLieId = keyof typeof DECLARATION_LIES;

export function isDeclarationLieId(id: string): id is DeclarationLieId {
  return Object.prototype.hasOwnProperty.call(DECLARATION_LIES, id);
}
